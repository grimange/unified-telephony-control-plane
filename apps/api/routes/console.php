Artisan::command('simulator:ensure-targets', function (ReconciliationRepository $repository): int {
    $count = 0;
    DB::table('runtime_nodes')
        ->where('adapter_key', config('simulator.adapter_key', 'simulator-deterministic'))
        ->whereIn('desired_state', ['active', 'draining'])
        ->orderBy('id')
        ->get()
        ->each(function (object $node) use ($repository, &$count): void {
            if (DB::table('simulator_profiles')->where('runtime_node_id', $node->id)->exists()) {
                $repository->ensureTarget((string) $node->tenant_id, 'runtime_node', (string) $node->id, (int) $node->configuration_version);
                $count++;
            }
        });
    $this->line('simulator_reconciliation_targets_ensured='.$count);

    return 0;
})->purpose('Automatically ensure reconciliation targets for active deterministic simulator nodes.');

