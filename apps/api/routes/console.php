Artisan::command('identity:bootstrap-local
    {--email=admin@utcp.local.test : Local administrator email}
    {--display-name=UTCP Local Administrator : Local administrator display name}
    {--password= : One-time bootstrap password; generated by wrapper when omitted}
    {--tenant-slug=local : Optional local tenant slug}
    {--tenant-name=Local Tenant : Optional local tenant display name}', function (AuditRepository $audit): int {
    $email = Str::lower((string) $this->option('email'));
    $displayName = trim((string) $this->option('display-name')) ?: 'UTCP Local Administrator';
    $password = (string) ($this->option('password') ?: 'utcp-'.bin2hex(random_bytes(12)));
    $tenantSlug = Str::slug((string) $this->option('tenant-slug')) ?: 'local';
    $tenantName = trim((string) $this->option('tenant-name')) ?: 'Local Tenant';

    $existingAdmin = DB::table('platform_role_assignments')
        ->where('role_key', 'platform-admin')
        ->value('user_id');

    if (is_string($existingAdmin)) {
        $this->info('A platform administrator already exists; bootstrap did not modify credentials.');

        return 0;
    }

    DB::transaction(function () use ($audit, $email, $displayName, $password, $tenantSlug, $tenantName): void {
        $now = now();
        $user = DB::table('users')->where('normalized_email', $email)->first();
        $userId = is_object($user) ? $user->id : IdentityIds::new();

        if (! is_object($user)) {
            DB::table('users')->insert([
                'id' => $userId,
                'email' => $email,
                'normalized_email' => $email,
                'display_name' => $displayName,
                'password' => Hash::make($password),
                'status' => 'active',
                'password_change_required' => false,
                'session_version' => 1,
                'password_changed_at' => $now,
                'created_at' => $now,
                'updated_at' => $now,
            ]);
        }

        DB::table('platform_role_assignments')->insert([
            'id' => IdentityIds::new(),
            'user_id' => $userId,
            'role_key' => 'platform-admin',
            'assigned_by_user_id' => null,
            'created_at' => $now,
        ]);

        $tenant = DB::table('tenants')->where('slug', $tenantSlug)->first();
        $tenantId = is_object($tenant) ? $tenant->id : IdentityIds::new();
        if (! is_object($tenant)) {
            DB::table('tenants')->insert([
                'id' => $tenantId,
                'slug' => $tenantSlug,
                'display_name' => $tenantName,
                'status' => 'active',
                'created_at' => $now,
                'updated_at' => $now,
            ]);
        }

        $membership = DB::table('tenant_memberships')->where('tenant_id', $tenantId)->where('user_id', $userId)->first();
        $membershipId = is_object($membership) ? $membership->id : IdentityIds::new();
        if (! is_object($membership)) {
            DB::table('tenant_memberships')->insert([
                'id' => $membershipId,
                'tenant_id' => $tenantId,
                'user_id' => $userId,
                'status' => 'active',
                'created_at' => $now,
                'updated_at' => $now,
            ]);
        }

        if (! DB::table('tenant_role_assignments')->where('membership_id', $membershipId)->where('role_key', 'tenant-admin')->exists()) {
            DB::table('tenant_role_assignments')->insert([
                'id' => IdentityIds::new(),
                'membership_id' => $membershipId,
                'role_key' => 'tenant-admin',
                'assigned_by_user_id' => null,
                'created_at' => $now,
            ]);
        }

        $context = ExecutionContext::system();
        $audit->append($context, 'identity.bootstrap.platform_admin_created', 'user', $userId, [
            'email_hash' => hash('sha256', $email),
        ]);
        $audit->append($context, 'identity.bootstrap.local_tenant_ready', 'tenant', $tenantId, [
            'slug' => $tenantSlug,
        ]);
    });

    $this->info('Local platform administrator bootstrap is ready. Credentials were not printed.');

    return 0;
})->purpose('Create the first local platform administrator when none exists.');

Artisan::command('identity:status', function (): int {
    $tables = ['users', 'tenants', 'tenant_memberships', 'roles', 'capabilities', 'sessions'];

    foreach ($tables as $table) {
        if (! Schema::hasTable($table)) {
            $this->line($table.'=missing');

            continue;
        }

        $this->line($table.'_count='.DB::table($table)->count());
    }

    if (Schema::hasTable('users')) {
        DB::table('users')
            ->select('status', DB::raw('count(*) as count'))
            ->groupBy('status')
            ->orderBy('status')
            ->get()
            ->each(fn (object $row) => $this->line('users_status_'.$row->status.'='.$row->count));
    }

    if (Schema::hasTable('tenants')) {
        DB::table('tenants')
            ->select('status', DB::raw('count(*) as count'))
            ->groupBy('status')
            ->orderBy('status')
            ->get()
            ->each(fn (object $row) => $this->line('tenants_status_'.$row->status.'='.$row->count));
    }

    if (Schema::hasTable('tenant_memberships')) {
        DB::table('tenant_memberships')
            ->select('status', DB::raw('count(*) as count'))
            ->groupBy('status')
            ->orderBy('status')
            ->get()
            ->each(fn (object $row) => $this->line('memberships_status_'.$row->status.'='.$row->count));
    }

    $this->line('catalog_version='.config('identity.catalog_version'));

    return 0;
})->purpose('Report non-sensitive identity and tenancy status.');

